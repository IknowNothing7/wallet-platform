package com.waller.wallet_platform.ledger.controller;

import com.waller.wallet_platform.account.entity.Account;
import com.waller.wallet_platform.account.repository.AccountRepository;
import com.waller.wallet_platform.ledger.dto.PostingRequest;
import com.waller.wallet_platform.ledger.entity.JournalEntry;
import com.waller.wallet_platform.ledger.entity.JournalEntryType;
import com.waller.wallet_platform.ledger.entity.PostingDirection;
import com.waller.wallet_platform.ledger.repository.JournalEntryRepository;
import com.waller.wallet_platform.ledger.repository.PostingRepository;
import com.waller.wallet_platform.security.JwtTokenProvider;
import com.waller.wallet_platform.user.entity.AppUser;
import com.waller.wallet_platform.user.entity.UserRole;
import com.waller.wallet_platform.user.repository.AppUserRepository;
import com.waller.wallet_platform.support.IntegrationTest;
import io.restassured.RestAssured;
import io.restassured.http.ContentType;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;

import java.util.List;

import static com.waller.wallet_platform.support.TestData.account;
import static com.waller.wallet_platform.support.TestData.user;
import static io.restassured.RestAssured.given;
import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.equalTo;
import static org.hamcrest.Matchers.hasSize;

public class PostingControllerTest extends IntegrationTest {

    @Autowired
    private PostingRepository postingRepository;
    @Autowired
    private JournalEntryRepository journalEntryRepository;
    @Autowired
    private AccountRepository accountRepository;
    @Autowired
    private AppUserRepository appUserRepository;
    @Autowired
    private JwtTokenProvider jwtTokenProvider;

    private AppUser admin;
    private Account aliceUsd;
    private Account bobUsd;
    private JournalEntry journalEntry;

    @BeforeEach
    void setUp() {
        admin = appUserRepository.save(user("Admin", "admin@email.com", UserRole.ADMIN));
        AppUser alice = appUserRepository.save(user("Alice", "alice@email.com", UserRole.USER));
        AppUser bob = appUserRepository.save(user("Bob", "bob@email.com", UserRole.USER));
        aliceUsd = accountRepository.save(account(alice, 1000, "USD"));
        bobUsd = accountRepository.save(account(bob, 0, "USD"));

        // The id is generated by the database, so it's read back rather than set here
        JournalEntry entry = new JournalEntry();
        entry.setEntryType(JournalEntryType.DEPOSIT);
        journalEntry = journalEntryRepository.save(entry);
    }

    @Test
    void createPostings_movesMoneyFromDebitedToCreditedAccount() {
        given()
                .auth().oauth2(jwtTokenProvider.generateToken(admin))
                .contentType(ContentType.JSON)
                .body(List.of(
                        new PostingRequest(aliceUsd.getId(), PostingDirection.DEBIT, 100L, "USD"),
                        new PostingRequest(bobUsd.getId(), PostingDirection.CREDIT, 100L, "USD")))
        .when()
                .post("/posting/journal-entry/{journalEntryId}", journalEntry.getId())
        .then()
                .statusCode(201)
                .body("success", equalTo(true))
                .body("payload", hasSize(2));

        assertThat(postingRepository.count()).isEqualTo(2);
        assertThat(accountRepository.findById(aliceUsd.getId()).orElseThrow().getBalance()).isEqualTo(900L);
        assertThat(accountRepository.findById(bobUsd.getId()).orElseThrow().getBalance()).isEqualTo(100L);
    }

    @Test
    void createPostings_unbalanced_returns400AndLeavesBalancesUnchanged() {
        given()
                .auth().oauth2(jwtTokenProvider.generateToken(admin))
                .contentType(ContentType.JSON)
                .body(List.of(
                        new PostingRequest(aliceUsd.getId(), PostingDirection.DEBIT, 100L, "USD"),
                        new PostingRequest(bobUsd.getId(), PostingDirection.CREDIT, 90L, "USD")))
        .when()
                .post("/posting/journal-entry/{journalEntryId}", journalEntry.getId())
        .then()
                .statusCode(400);

        assertThat(postingRepository.count()).isZero();
        assertThat(accountRepository.findById(aliceUsd.getId()).orElseThrow().getBalance()).isEqualTo(1000L);
        assertThat(accountRepository.findById(bobUsd.getId()).orElseThrow().getBalance()).isZero();
    }

    @Test
    void createPostings_nonAdminIsForbidden() {
        AppUser alice = aliceUsd.getUser();
        given()
                .auth().oauth2(jwtTokenProvider.generateToken(alice))
                .contentType(ContentType.JSON)
                .body(List.of(
                        new PostingRequest(aliceUsd.getId(), PostingDirection.DEBIT, 100L, "USD"),
                        new PostingRequest(bobUsd.getId(), PostingDirection.CREDIT, 100L, "USD")))
        .when()
                .post("/posting/journal-entry/{journalEntryId}", journalEntry.getId())
        .then()
                .statusCode(403);

        assertThat(postingRepository.count()).isZero();
    }
}
